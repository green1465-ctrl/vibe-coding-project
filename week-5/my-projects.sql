-- 기존에 있으면 지우고 새로 만들기 (실습용이라 안전)
DROP TABLE IF EXISTS "W5_my_projects";

CREATE TABLE "W5_my_projects" (
  id          BIGSERIAL PRIMARY KEY,
  title       VARCHAR(100)  NOT NULL,            -- 프로젝트명
  client      VARCHAR(100),                      -- 클라이언트 (개인작업이면 NULL)
  category    VARCHAR(30)   NOT NULL,            -- '로고','브랜딩','웹디자인','제품디자인','학습'
  status      VARCHAR(20)   NOT NULL,            -- '완료','진행중','보류'
  start_date  DATE,
  end_date    DATE,                              -- 진행중이면 NULL
  tools       TEXT,                              -- 'Framer, Figma, Illustrator' 식
  fee         BIGINT,                            -- 작업비 (원). 학습/개인작업은 0
  satisfaction SMALLINT,                         -- 만족도 1~5
  memo        TEXT,
  created_at  TIMESTAMPTZ DEFAULT NOW()
);


